def profile_choices() -> list[tuple[str, str]]:
    """‏(مفتاح، تسمية) لكل ملفّ — لبناء قائمة الواجهة."""
    return [(p.key, p.label) for p in PROFILES.values()]


def apply_profile(config, key: str):
    """يُعيد نسخة من الإعداد بعد تطبيق ملفّ المحتوى.

    لا يُعدّل الأصل: الـpipeline يبني بصمة المعالجة من قيم الإعداد
    الفعلية، فتغيير الملفّ يُبطل المراحل المخزّنة تلقائيًا ويُعاد بناء
    المشاهد والصور — وهو السلوك الصحيح، لأن الملفّ يغيّرها فعلًا.

    مفتاح غير معروف يُعيد الإعداد كما هو بدل أن يرفع استثناء: ملف إعداد
    من إصدار أحدث لا يجوز أن يمنع الإقلاع.
    """
    profile = PROFILES.get(key)
    if profile is None or not profile.overrides:
        return config

    updates = {}
    for section, values in profile.overrides.items():
        current = getattr(config, section, None)
        if current is None:               # قسم غير موجود في هذا الإصدار
            continue
        updates[section] = current.model_copy(update=values)
    return config.model_copy(update=updates)
